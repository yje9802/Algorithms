WITH LENGTH_AVG AS (
    SELECT FISH_TYPE,
        AVG(COALESCE(LENGTH, 10)) AS AVG_LENGTH,
        COUNT(*) AS FISH_COUNT
    FROM FISH_INFO
    GROUP BY FISH_TYPE
    HAVING AVG(COALESCE(LENGTH, 10)) >= 33
)

SELECT A.FISH_COUNT, MAX(LENGTH) AS MAX_LENGTH, I.FISH_TYPE
FROM FISH_INFO I JOIN LENGTH_AVG A ON I.FISH_TYPE = A.FISH_TYPE
GROUP BY I.FISH_TYPE
ORDER BY I.FISH_TYPE