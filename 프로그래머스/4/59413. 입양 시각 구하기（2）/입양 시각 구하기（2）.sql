WITH RECURSIVE HOURS AS (
    SELECT 0 AS HOUR
    
    UNION ALL
    
    SELECT HOUR + 1 AS HOUR
    FROM HOURS
    WHERE HOUR < 23
), OUT_HOURS AS (
    SELECT HOUR(DATETIME) AS OUT_HOUR
    FROM ANIMAL_OUTS
)

SELECT H.HOUR, 
    CASE
        WHEN O.OUT_HOUR IS NULL THEN 0
        ELSE COUNT(*)
    END AS COUNT
FROM HOURS H
    LEFT JOIN OUT_HOURS O ON H.HOUR = O.OUT_HOUR
GROUP BY H.HOUR
ORDER BY H.HOUR